package com.elladecide.lola.emoji

/**
 * Categorías del panel de emojis. [icon] es el glifo que se muestra en la pestaña.
 */
enum class EmojiCategory(val icon: String) {
    RECENT("🕐"),
    SMILEYS("😀"),
    PEOPLE("👋"),
    ANIMALS("🐾"),
    FOOD("🍽"),
    ACTIVITY("⚽"),
    TRAVEL("✈"),
    OBJECTS("💡"),
    SYMBOLS("❤"),
}
